test("a failed plan is researched, rebuilt and executed without repeating the accepted prefix or discarding its candidate", async t => {
  const f = executionFixture(t, "repair");
  const initial = await f.engine.executor.run("p", reference(f.plan), f.options);
  assert.deepEqual(initial.map(run => run.value.state), ["committed", "needs_plan"]);
  const failed = initial[1]!, previousRoot = f.store.get<ExecutionRoot>("execution-root:p")!;
  const candidate = readFileSync(join(previousRoot.value.path, "consume.mjs"), "utf8");
  const design = structuredClone(f.plan.value.graphSnapshot); design.horizon = ["p-consume-work"];
  const consumerTest = design.tests.find(test => test.node === "p-consume-work")!;
  consumerTest.covers.push("p-flow");
  consumerTest.contract!.counterfactuals.push({ connector: "p-flow", mutation: "remove", expectedFailure: "input_missing", command: { executable: process.execPath, args: ["check.mjs", "consume-mutation"] } });
  writeFileSync(join(f.directory, "calls.jsonl.repair.json"), JSON.stringify({ design: layerDesignOf(design, 3, L3_ASSEMBLY) }));
  const first = await f.engine.execute({ type: "repair-plan", project: "p", run: reference(failed), maxTurns: 1 }) as Revision<PlanRepair>;
  assert.equal(first.value.phase, "research"); assert.ok(first.value.error);
  const parked = f.store.get<ParkedCandidate>(first.value.parked.id)!;
  assert.equal(parked.value.state, "parked");
  const nextRoot = f.store.get<ExecutionRoot>("execution-root:p")!;
  assert.notEqual(nextRoot.value.path, previousRoot.value.path);
  assert.equal(nextRoot.value.head, initial[0]!.value.commit);
  assert.equal(git(nextRoot.value.path, ["status", "--porcelain"]), "");
  assert.equal(existsSync(join(nextRoot.value.path, "consume.mjs")), false);
  assert.equal(readFileSync(join(previousRoot.value.path, "consume.mjs"), "utf8"), candidate);
  assert.equal(git(previousRoot.value.path, ["rev-parse", parked.value.archiveRef]), failed.value.tree);
  const draft = f.store.get<DiscoveryDraft>(first.value.draftId)!;
  assert.ok(draft.value.questions.map(id => f.store.get<Question>(id)!.value.spec).some(spec => spec.targets?.some(target => target.target === "p-consume-work")));
  assert.equal(researchGraphContext(f.store, draft.value)!.failures.length, 1);
  const answered = draft.value.questions.filter(id => f.store.get<Question>(id)!.value.status === "answered");
  assert.equal(answered.length, 1);
  const before = f.store.get(answered[0]!)!;
  f.reopen();
  const complete = await f.engine.repairs.run("p", reference(failed), 20);
  assert.equal(complete.value.phase, "reissued", complete.value.error ?? "Repair failed");
  assert.equal(f.store.get(before.id)!.revision, before.revision, "Resuming repair must reuse its accepted answer");
  const plan = f.engine.compiler.read(complete.value.plan!.id);
  assert.deepEqual(plan.value.tasks.map(task => task.node), ["p-consume-work"]);
  assert.ok(plan.value.tasks[0]!.inputs[0]!.receipt);
  assert.deepEqual(f.engine.compiler.gate("p", reference(plan)).findings, [], "Recording a reissue cannot invalidate its own research");
  const calls = f.calls().length;
  assert.deepEqual(await f.engine.repairs.run("p", reference(failed), 20), complete);
  assert.equal(f.calls().length, calls);
  const result = await f.engine.executor.run("p", reference(plan), f.options);
  assert.equal(result[0]!.value.state, "committed", result[0]!.value.error ?? "Execution failed");
  assert.equal(f.calls().filter(call => call.mode === "implement" && call.task === f.plan.value.tasks[0]!.id).length, 1);
  assert.equal(f.store.get(failed.id, failed.revision)!.hash, failed.hash);
});

test("repair refuses changed candidate bytes and a foreign run without rotating away user edits", async t => {
  const f = executionFixture(t, "plan-defect");
  const runs = await f.engine.executor.run("p", reference(f.plan), f.options), failed = runs[0]!;
  const root = f.store.get<ExecutionRoot>("execution-root:p")!;
  const path = join(root.value.path, "produce.mjs");
  writeFileSync(path, readFileSync(path, "utf8") + "\n// new owner edit\n");
  await assert.rejects(f.engine.repairs.prepare("p", reference(failed)), /New edits appeared/);
  assert.equal(f.store.get(root.id)!.hash, root.hash);
  assert.match(readFileSync(path, "utf8"), /new owner edit/);
  await assert.rejects(f.engine.repairs.prepare("other-project", reference(failed)), /exact plan defect/);
  assert.equal(f.store.list<PlanDefect>("plan-defect").length, 0);
});

test("research cannot reissue an unchanged accepted prefix as new work", async t => {
  const f = executionFixture(t, "repair");
  const runs = await f.engine.executor.run("p", reference(f.plan), f.options);
  const design = structuredClone(f.plan.value.graphSnapshot);
  writeFileSync(join(f.directory, "calls.jsonl.repair.json"), JSON.stringify({ design: layerDesignOf(design, 3, L3_ASSEMBLY) }));
  const result = await f.engine.repairs.run("p", reference(runs[1]!), 20);
  assert.equal(result.value.phase, "design"); assert.match(result.value.error!, /repeat an unchanged accepted unit/);
  assert.equal(f.store.list("plan-reissue").length, 0);
  const draft = f.store.get<DiscoveryDraft>(result.value.draftId)!;
  assert.equal(f.store.get<Question>(draft.value.questions[0]!)!.value.status, "open");
  assert.ok(f.store.list("source").some(source => source.id.includes(":repair-feedback-")));
  design.horizon = ["p-consume-work"];
  const check = design.tests.find(test => test.node === "p-consume-work")!;
  check.covers = ["p-flow"];
  check.contract!.counterfactuals = [{ connector: "p-flow", mutation: "remove", expectedFailure: "input_missing", command: { executable: process.execPath, args: ["check.mjs", "consume-mutation"] } }];
  writeFileSync(join(f.directory, "calls.jsonl.repair.json"), JSON.stringify({ design: layerDesignOf(design, 3, L3_ASSEMBLY) }));
  const corrected = await f.engine.repairs.run("p", reference(runs[1]!), 10);
  assert.equal(corrected.value.phase, "reissued", corrected.value.error ?? "Correction failed");
});

test("an early technical refusal preserves accepted reports and the next model call can repair it", async t => {
  const f = executionFixture(t, "repair");
  const failed = (await f.engine.executor.run("p", reference(f.plan), f.options))[1]!;
  const graph = structuredClone(f.plan.value.graphSnapshot); graph.horizon = ["p-consume-work"];
  const check = graph.tests.find(test => test.node === "p-consume-work")!;
  check.covers = ["p-flow"];
  check.contract!.counterfactuals = [{ connector: "p-flow", mutation: "remove", expectedFailure: "input_missing", command: { executable: process.execPath, args: ["check.mjs", "consume-mutation"] } }];
  const prepared=await f.engine.repairs.prepare("p",reference(failed));
  const initialDraft=f.store.get<DiscoveryDraft>(prepared.value.draftId)!;
  answerTechnicalFixture(f.engine,"p",{...initialDraft,value:{...initialDraft.value,
    questions:initialDraft.value.questions.filter(id=>f.store.get<Question>(id)!.value.spec.field!=="contractsAndConsumers")}});
  writeFileSync(join(f.directory, "calls.jsonl.repair.json"), JSON.stringify({ design: layerDesignOf(graph, 3, L3_ASSEMBLY), researchGap: true }));
  const rejected = await f.engine.repairs.run("p", reference(failed), 20);
  assert.equal(rejected.value.phase, "research"); assert.match(rejected.value.error!, /Research turn allowance reached/);
  assert.ok(f.store.list("research-turn").some(turn => JSON.stringify(turn.value).includes("research_gap_unresolved")));
  const draft = f.store.get<DiscoveryDraft>(rejected.value.draftId)!;
  const questions = draft.value.questions.map(id => f.store.get<Question>(id)!);
  assert.deepEqual(questions.filter(question => question.value.status === "open").map(question => question.value.spec.field), ["contractsAndConsumers"]);
  const accepted = questions.filter(question => question.value.status === "answered");
  const calls = f.calls().length;
  writeFileSync(join(f.directory, "calls.jsonl.repair.json"), JSON.stringify({ design: layerDesignOf(graph, 3, L3_ASSEMBLY), researchGap: false }));
  const corrected = await f.engine.repairs.run("p", reference(failed), 20);
  assert.equal(corrected.value.phase, "reissued", corrected.value.error ?? "Repair failed");
  assert.ok(f.calls().length > calls);
  for (const question of accepted) assert.equal(f.store.get(question.id)!.revision, question.revision);
});
