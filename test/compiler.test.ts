import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Store } from "../src/storage/store.js";
import { ProductEngine } from "../src/product/engine.js";
import { prepareOmFixtureStages, prepareNativeLayers } from "./om-fixture.js";
import { enrichedGraph } from "./enriched-graph-fixture.js";
import { exampleGraph } from "./graph-fixture.js";
import { git } from "../src/runtime/environment.js";
import { reference } from "../src/pipeline/contracts.js";
import { consumePlan } from "../src/compiler/consumer.js";
import { validateGraph } from "../src/graph/validate.js";
import { deriveTasks } from "../src/compiler/derive.js";
import { hashJson } from "../src/canonical.js";

test("machine tasks, dependencies and required durable checks are derived without manual cards and consumed in order", async t => {
  const root = mkdtempSync(join(tmpdir(), "omg-compile-")); const workspace = join(root, "repo"); mkdirSync(workspace);
  git(workspace, ["init", "-b", "main"]); writeFileSync(join(workspace, "README.md"), "Compiler input repository\n");
  git(workspace, ["add", "README.md"]); git(workspace, ["-c", "user.name=OMG Test", "-c", "user.email=test@example.invalid", "commit", "-m", "initial"]);
  const store = new Store(join(root, "state.sqlite")); const engine = new ProductEngine(store);
  t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
  const graph = exampleGraph("garden");
  for (const node of graph.nodes.filter(node => ["garden-produce-work", "garden-produce-operation"].includes(node.id))) node.boundary = { ...node.boundary, state: "durable" };
  assert.ok(validateGraph(graph).findings.some(f => f.code === "test_obligation_missing"));
  graph.tests[0]!.obligations = ["outcome", "restart_cold", "durable_cold_read"];
  const desired = enrichedGraph(graph, "garden");
  prepareOmFixtureStages(engine, "garden", desired);
  const command = { executable: process.execPath, args: ["--version"] };
  engine.environments.configure("garden", { workspace, implementer: { actor: "worker", model: "fixture", effort: "high", command },
    reviewer: { actor: "reviewer", model: "fixture", effort: "high", command }, fullCheck: command, timeoutMs: 1000, requestCapacityChars: 100_000 }, 0);
  assert.throws(() => engine.compiler.compile("garden"), /OM-G2 must be accepted/);
  prepareNativeLayers(engine, "garden", desired, "executed", { decidePolicies: true });
  const plan = engine.compiler.compile("garden"); const again = engine.compiler.compile("garden");
  assert.deepEqual(again, plan); assert.equal(store.list("plan").length, 1);
  assert.equal(plan.value.tasks.length, 2);
  assert.deepEqual(plan.value.tasks[1]!.dependencies, [plan.value.tasks[0]!.id]);
  assert.equal(plan.value.tasks[0]!.obligations.find(item => item.name === "durable_cold_read")!.status, "required");
  assert.deepEqual(engine.compiler.read(plan.id), plan);
  const changed = structuredClone(graph);
  changed.connectors[0]!.bindings = changed.connectors[0]!.bindings.filter(binding => binding.level !== 3);
  const unconnected = deriveTasks("garden", "another-version", changed, () => { throw new Error("No external input expected"); });
  assert.ok(unconnected.tasks.every(task => task.dependencies.length === 0), "Removing the L3 connector must remove the compiled dependency");
  const preview = join(root, "preview"); mkdirSync(preview);
  const consumed = await consumePlan(plan.value, { async execute(task) {
    for (const path of task.writePaths) writeFileSync(join(preview, path), task.title);
    return { taskId: task.id, outcome: task.outcome };
  } });
  assert.equal(consumed.mode, "preview"); assert.equal(readFileSync(join(preview, "consume.txt"), "utf8"), "consume work");
  engine.execute({ type: "compile", project: "garden" });
  assert.equal(engine.pipeline.inspect("garden", "compilation").state, "accepted");
  engine.discovery.evidence.document("garden", "brief", "changed brief", "text/plain", 1);
  assert.ok(engine.compiler.gate("garden", reference(plan)).findings.some(item => item.code === "plan_stale"));
  const forged = structuredClone(plan.value); forged.tasks[0]!.writePaths.push("unrelated.txt");
  const { hash: _hash, ...body } = forged; forged.hash = hashJson(body);
  store.write({ id: plan.id, kind: "plan", expected: plan.revision, value: forged });
  assert.throws(() => engine.compiler.read(plan.id), /Tasks must be derived/, "A valid checksum cannot authorize a manually edited task");
  const stripped = structuredClone(plan.value); stripped.guards = [];
  const { hash: _strippedHash, ...strippedBody } = stripped; stripped.hash = hashJson(strippedBody);
  const strippedRecord = store.write({ id: plan.id, kind: "plan", expected: 2, value: stripped });
  assert.throws(() => engine.compiler.gate("garden", reference(strippedRecord)), /cannot omit evidence/);
  const foreignBase = structuredClone(plan.value); foreignBase.base.head = "0".repeat(40);
  const { hash: _baseHash, ...baseBody } = foreignBase; foreignBase.hash = hashJson(baseBody);
  store.write({ id: plan.id, kind: "plan", expected: 3, value: foreignBase });
  assert.throws(() => engine.compiler.read(plan.id), /sealed R3 basis/);
});
